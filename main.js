  const PH = () => `<div class="img-ph"><svg fill="none" stroke="#E8897A" stroke-width="1.5" viewBox="0 0 24 24"><path stroke-linecap="round" stroke-linejoin="round" d="M2.25 15.75l5.159-5.159a2.25 2.25 0 013.182 0l5.159 5.159m-1.5-1.5l1.409-1.409a2.25 2.25 0 013.182 0l2.909 2.909M3 21h18M3.75 3h16.5M4.5 3v18M19.5 3v18"/></svg><span>Imagem em breve</span></div>`;
  const lapFr  = img => `<div class="d-lap"><div class="dl-wrap"><div class="dl-screen">${img?`<img src="${img}" alt="" loading="lazy" decoding="async">`:`${PH()}`}</div></div><div class="dl-base"></div><div class="dl-foot"></div></div>`;
  const phFr   = img => `<div class="d-ph"><div class="dp-screen">${img?`<img src="${img}" alt="" loading="lazy" decoding="async">`:`${PH()}`}</div></div>`;
  const grFr   = (img,label) => `<div class="d-gr">${img?`<img src="${img}" alt="${label}" loading="lazy" decoding="async">`:`${PH()}`}</div>`;

  function renderProject(id) {
    const p = P[id]; if (!p) return '<p style="padding:48px">Projeto não encontrado.</p>';
    const tools = p.tools.map(t=>`<span class="pill">${t}</span>`).join('');
    const hasExternalProject = p.cat !== 'Design Gráfico' && p.showCta !== false;
    const cta = p.type === 'figma'
      ? `<a class="btn btn-p" href="${p.url}" target="_blank">${p.ctaLabel} ↗</a>`
      : `<button class="btn btn-p" onclick="openModal('${id}')">${p.ctaLabel}</button>`;
    const items = p.delivs.map(d => {
      const fr = p.device==='desktop' ? lapFr(d.img) : p.device==='mobile' ? phFr(d.img) : grFr(d.img,d.label);
      const preview = d.img
        ? `<div class="zoomable" role="button" tabindex="0" aria-label="Ampliar ${d.label}" data-img="${encodeURIComponent(d.img)}" data-label="${encodeURIComponent(d.label)}" onclick="openImage(decodeURIComponent(this.dataset.img),decodeURIComponent(this.dataset.label))" onkeydown="if(event.key==='Enter'||event.key===' '){event.preventDefault();this.click()}">${fr}</div>`
        : fr;
      return `<div>${preview}<div class="deliv-label">${d.label}</div></div>`;
    }).join('');
    return `
      <section class="proj-hero">
        <div class="proj-crumb">Portfolio <span>›</span> ${p.cat}</div>
        <h1>${p.title}<br><em>${p.subtitle}</em></h1>
        <p>${p.desc}</p>
        <div class="pills" style="margin-top:24px">${tools}</div>
      </section>
      <div class="proj-main project-${id}">
        <div class="case-grid" aria-label="Resumo do projeto">
          <article class="case-item"><h2>Problema</h2><p>${p.problem}</p></article>
          <article class="case-item"><h2>Solução</h2><p>${p.solution}</p></article>
          <article class="case-item"><h2>Tecnologias</h2><p>${p.tools.join(' · ')}</p></article>
          <article class="case-item"><h2>Resultado</h2><p>${p.result}</p></article>
        </div>
        ${hasExternalProject ? `<div class="proto-cta"><div><h3>${p.ctaLabel}</h3><p>${p.ctaNote}</p></div>${cta}</div>` : ''}
        ${items ? `<div class="deliv-title">Entregas do Projeto</div><div class="deliv-grid">${items}</div>` : ''}
      </div>`;
  }

  function openModal(id) {
    const p = P[id]; if (!p) return;
    document.getElementById('modal-title').textContent = p.title + ' — Protótipo';
    document.getElementById('modal-ext').href = p.url;
    const d = document.getElementById('modal-device');
    d.innerHTML = p.device === 'mobile'
      ? `<div class="m-ph"><div class="mp-frame"><div class="mp-screen"><iframe src="${p.url}" title="${p.title}" allow="fullscreen"></iframe></div></div></div>`
      : `<div class="m-lap"><div class="ml-wrap"><div class="ml-screen"><iframe src="${p.url}" title="${p.title}" allow="fullscreen"></iframe></div></div><div class="ml-base"></div><div class="ml-foot"></div></div>`;
    document.getElementById('proto-modal').classList.add('open');
    document.body.style.overflow = 'hidden';
  }
  function closeModal() {
    document.getElementById('proto-modal').classList.remove('open');
    document.getElementById('modal-device').innerHTML = '';
    document.body.style.overflow = '';
  }
  document.getElementById('proto-modal').addEventListener('click', e => { if (e.target.id==='proto-modal') closeModal(); });
  function openImage(src, label) {
    const modal = document.getElementById('image-modal');
    const image = document.getElementById('image-modal-img');
    document.getElementById('image-modal-title').textContent = label || 'Imagem do projeto';
    image.src = src;
    image.alt = label || 'Imagem ampliada do projeto';
    modal.classList.add('open');
    document.body.style.overflow = 'hidden';
    document.getElementById('image-modal-close').focus();
  }
  function closeImage() {
    const modal = document.getElementById('image-modal');
    modal.classList.remove('open');
    document.getElementById('image-modal-img').src = '';
    document.body.style.overflow = '';
  }
  document.getElementById('image-modal').addEventListener('click', e => { if (e.target.id==='image-modal') closeImage(); });
  document.addEventListener('keydown', e => {
    if (e.key !== 'Escape') return;
    if (document.getElementById('image-modal').classList.contains('open')) closeImage();
    else closeModal();
  });

  let curView = 'home';
  function closeMenu() {
    const links = document.querySelector('.nav-links');
    const toggle = document.getElementById('menu-toggle');
    links.classList.remove('open');
    toggle.classList.remove('open');
    toggle.setAttribute('aria-expanded', 'false');
    toggle.setAttribute('aria-label', 'Abrir menu');
  }
  function toggleMenu() {
    const links = document.querySelector('.nav-links');
    const toggle = document.getElementById('menu-toggle');
    const isOpen = links.classList.toggle('open');
    toggle.classList.toggle('open', isOpen);
    toggle.setAttribute('aria-expanded', String(isOpen));
    toggle.setAttribute('aria-label', isOpen ? 'Fechar menu' : 'Abrir menu');
  }
  function showView(name) {
    closeMenu();
    document.querySelectorAll('.view').forEach(v => v.classList.remove('active'));
    const nextView = document.getElementById('view-' + name);
    nextView.classList.add('active');
    window.scrollTo({ top: 0, behavior: 'auto' });
    curView = name;

    requestAnimationFrame(() => observeCards(nextView));
  }
  function openProject(id) {
    if (!P[id]) return;
    document.getElementById('proj-content').innerHTML = renderProject(id);
    showView('project');
    document.getElementById('nav').classList.add('proj');
    document.title = P[id].title + ' | Case de Tabatha Nakajima';
    setTimeout(observeCards, 80);
  }
  function goHome() {
    showView('home');
    document.getElementById('nav').classList.remove('proj');
    document.title = 'Tabatha Nakajima | Desenvolvedora Web & UX/UI Designer';
  }
  function goSection(id) {
    closeMenu();
    if (curView !== 'home') {
      goHome();
      setTimeout(() => document.getElementById(id)?.scrollIntoView({ behavior: 'smooth' }), 450);
    } else {
      document.getElementById(id)?.scrollIntoView({ behavior: 'smooth' });
    }
  }
  window.addEventListener('resize', () => { if (window.innerWidth > 900) closeMenu(); });

  document.querySelectorAll('.current-year').forEach(el => {
    el.textContent = new Date().getFullYear();
  });

  const btt = document.getElementById('btt');
  window.addEventListener('scroll', () => btt.classList.toggle('vis', window.scrollY > 300));
  btt.addEventListener('click', () => window.scrollTo({ top: 0, behavior: 'smooth' }));

  const obs = new IntersectionObserver(entries => {
    entries.forEach(e => { if (e.isIntersecting) { e.target.style.opacity='1'; e.target.style.transform='translateY(0)'; } });
  }, { threshold: 0.06 });

  function observeCards(root = document) {
    root.querySelectorAll('a.card').forEach(card => {
      if (card.dataset.keyboardReady) return;
      card.setAttribute('role', 'button');
      card.setAttribute('tabindex', '0');
      card.addEventListener('keydown', event => {
        if (event.key === 'Enter' || event.key === ' ') {
          event.preventDefault();
          card.click();
        }
      });
      card.dataset.keyboardReady = 'true';
    });
    root.querySelectorAll('.card, .section-header, .about-wrap, .contact-bar, .proto-cta, .deliv-grid > div').forEach(el => {
      el.style.opacity = '0'; el.style.transform = 'translateY(18px)';
      el.style.transition = 'opacity .5s ease, transform .5s ease';
      obs.observe(el);
    });

    requestAnimationFrame(() => {
      root.querySelectorAll('.card, .section-header, .about-wrap, .contact-bar, .proto-cta, .deliv-grid > div').forEach(el => {
        const rect = el.getBoundingClientRect();
        if (rect.top < window.innerHeight && rect.bottom > 0) {
          el.style.opacity = '1';
          el.style.transform = 'translateY(0)';
        }
      });
    });
  }
  observeCards();
